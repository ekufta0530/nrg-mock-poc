#!/usr/bin/env bash
# Build/push the two images and point the Argo CD overlay at them. Nothing is applied to the
# cluster directly: Argo CD syncs from Git.
#
#   scripts/deploy.sh --build [--push]     build + push to ECR, rewrite the images component
#   scripts/deploy.sh [--push]             just rewrite the images component for $TAG
#   TAG=1.0.1 scripts/deploy.sh --build --push
#
# --push commits the generated component and pushes it, then asks Argo CD to refresh.
. "$(dirname "$0")/lib.sh"

BUILD=false; PUSH=false
for a in "$@"; do
  case "$a" in
    --build) BUILD=true ;;
    --push)  PUSH=true ;;
    *) die "unknown flag $a" ;;
  esac
done

ensure_account
$BUILD && TAG="$TAG" "$ROOT/images/build.sh"

REG="$(tf_out ecr_registry)"
COMP="$OVERLAY/components/images/kustomization.yaml"
log "writing $COMP ($REG, tag $TAG)"
cat > "$COMP" <<YAML
# GENERATED by scripts/deploy.sh. Do not edit by hand.
apiVersion: kustomize.config.k8s.io/v1alpha1
kind: Component
images:
  - name: nrg-worker
    newName: $REG/nrg-worker
    newTag: "$TAG"
  - name: nrg-loadgen
    newName: $REG/nrg-loadgen
    newTag: "$TAG"
YAML

kubectl kustomize "$OVERLAY" >/dev/null && log "overlay renders cleanly"

if $PUSH; then
  git_push_paths "images: $TAG" "$COMP"
  argo_refresh nrg-workloads
else
  log "not pushed. Commit + push $COMP (or re-run with --push) so Argo CD picks it up."
fi
